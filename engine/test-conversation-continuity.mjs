import assert from 'node:assert/strict';
import {callNotes,callContext} from './call-memory.mjs';
import {completedThought,currentCoachTurn} from './coach-timing.mjs';
const t=(id,text,side='customer',who='Jesse')=>({id,text,side,who,me:side==='seller'});
const history=[t(1,'How much firewall data are you bringing in?','seller','Rodney'),t(2,'We ingest 45 gigs of firewall logs.'),t(3,'Actually, I meant roughly 46 gigs of firewall logs.'),t(4,'We retain endpoint logs for 30 days.'),t(5,'Actually, we retain firewall logs for 90 days.'),t(6,'We ingest 80 gigs of firewall logs.','customer','Joe'),...Array.from({length:25},(_,i)=>t(i+10,'Let me show you the dashboard and this search workflow.','presenter','Abby'))];
const notes=callNotes(history), context=callContext(history,notes,'Expected volume: 100 gigs');
assert.equal(notes.find(n=>n.turnId===2).supersededBy,3);
assert.equal(notes.find(n=>n.turnId===3).correctsTurnId,2);
assert.equal(notes.find(n=>n.turnId===3).tentative,true);
assert.equal(notes.find(n=>n.turnId===4).supersededBy,undefined,'different log source is not a correction');
assert.equal(notes.find(n=>n.turnId===6).supersededBy,undefined,'other customer retains their own statement');
assert.ok(context.includes('roughly 46 gigs'));
assert.ok(!context.includes('cust: We ingest 45 gigs'),'obsolete fact removed from current memory');
assert.ok(context.includes('Previously asked and answered'));
assert.ok(context.includes('Preparation (unconfirmed'));
const recent=callContext(history.slice(0,6),callNotes(history.slice(0,6)));
assert.ok(recent.includes('superseded by explicit customer correction'));
const unknown=callNotes([t(1,'We ingest 45 gigs of firewall logs.','unknown'),t(2,'Actually, we ingest 46 gigs of firewall logs.','unknown')]);
assert.ok(!unknown.some(n=>n.supersededBy),'unconfirmed speaker identity cannot supersede another statement');
assert.equal(completedThought('The investigation takes hours because'),false);
assert.equal(completedThought('We use several tools, including'),false);
assert.equal(completedThought('The investigation takes hours because we wait for the network team.'),true);
assert.equal(completedThought('We need to reduce triage time'),true,'missing punctuation alone does not imply unfinished speech');
assert.equal(currentCoachTurn(t(1,'Our analysts wait for firewall logs.'),t(2,'Let me answer that.','seller')),false);
assert.equal(currentCoachTurn(t(2,'Our analysts wait for firewall logs.'),t(2,'Our analysts wait for firewall logs.')),true);
console.log('PASS corrections, uncertainty, topic/speaker separation, long-call answered history and completed-thought timing');
